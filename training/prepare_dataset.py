"""
Builds a fine-tuning dataset for the noul question "is this text AI-generated?"
in the schema that Laya's Kaggle notebook expects
(laya_finetune_typed_decisions_2xT4_kaggle.ipynb, see ../RESOURCES.md and
README.md in this folder). Each row gets three JSON-encoded columns:

    state:     {"candidates": [{"text": "..."}]}
    questions: {"ai_generated": {"type": "noul", "instructions": "..."}}
    gold:      {"ai_generated": {"probabilities": {"true": p, "false": 1 - p}}}

Primary source: HC3 (Hello-SimpleAI/HC3, config "all") - human_answers vs.
chatgpt_answers, already paired 1:1 per question, hence balanced by nature.
RAID (for robustness against reworded/adversarial AI text) is deliberately NOT
implemented - the exact human-vs-model row schema was only read from the dataset card
in this session, not verified on real rows. See README.md.

Usage:
    pip install -r requirements.txt
    python prepare_dataset.py --out-dir data --limit 2000   # smoke test, small
    python prepare_dataset.py --out-dir data                # full dataset
"""

import argparse
import json
import random
from pathlib import Path

# modelled on content.js (extension/content.js), so that the training and
# inference distribution of text length match
MIN_WORDS = 40
MAX_CHARS = 2000  # content.js cuts at the sentence end, here hard - irrelevant for the length distribution

AI_GENERATED_INSTRUCTIONS = (
    "Is this text primarily generated by an AI/LLM, rather than written by a human? "
    "Judge only the writing style/patterns, not the topic or correctness."
)

# soft instead of hard labels (0.95/0.05 instead of 1.0/0.0), so that the model is not
# calibrated overconfidently - matching the notebook's RLCD/proper-scoring-rule
# training
SOFT_LABEL = 0.95


def word_count(text: str) -> int:
    return len(text.split())


def iter_hc3_pairs(source: str = "all"):
    """Yields (text, is_ai) pairs from HC3. Requires `datasets`.

    HC3's own loading script (`name=<subset>`) is no longer supported by current `datasets`
    versions ("Dataset scripts are no longer
    supported") - load via the Parquet branch automatically
    generated by HF instead (one split with all domains, the `source` column
    distinguishes reddit_eli5/finance/medicine/open_qa/wiki_csai).
    """
    from datasets import load_dataset

    ds = load_dataset("Hello-SimpleAI/HC3", revision="refs/convert/parquet")
    split = ds["train"] if "train" in ds else next(iter(ds.values()))
    if source != "all":
        split = split.filter(lambda r: r["source"] == source)

    for row in split:
        for human_text in row.get("human_answers") or []:
            yield human_text, False
        for ai_text in row.get("chatgpt_answers") or []:
            yield ai_text, True


def to_training_row(text: str, is_ai: bool) -> dict:
    text = text.strip()[:MAX_CHARS]
    p_true = SOFT_LABEL if is_ai else (1.0 - SOFT_LABEL)
    state = {"candidates": [{"text": text}]}
    questions = {
        "ai_generated": {"type": "noul", "instructions": AI_GENERATED_INSTRUCTIONS}
    }
    gold = {
        "ai_generated": {
            "probabilities": {"true": round(p_true, 4), "false": round(1 - p_true, 4)}
        }
    }
    return {
        "state": json.dumps(state, ensure_ascii=False),
        "questions": json.dumps(questions, ensure_ascii=False),
        "gold": json.dumps(gold, ensure_ascii=False),
    }


def write_jsonl(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", default="data")
    parser.add_argument("--config", default="all", help="HC3 domain (all/finance/medicine/open_qa/reddit_eli5/wiki_csai)")
    parser.add_argument("--min-words", type=int, default=MIN_WORDS)
    parser.add_argument("--train-frac", type=float, default=0.9)
    parser.add_argument("--limit", type=int, default=None, help="Take only the first N pairs (smoke test)")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    random.seed(args.seed)

    pairs = []
    for text, is_ai in iter_hc3_pairs(args.config):
        if word_count(text) < args.min_words:
            continue
        pairs.append((text, is_ai))
        if args.limit and len(pairs) >= args.limit:
            break

    if not pairs:
        raise SystemExit("No matching examples found - check the HC3 config/filter.")

    n_human = sum(1 for _, is_ai in pairs if not is_ai)
    n_ai = sum(1 for _, is_ai in pairs if is_ai)
    print(f"Collected: {len(pairs)} examples ({n_human} human, {n_ai} AI)")

    random.shuffle(pairs)
    split_idx = int(len(pairs) * args.train_frac)
    train_pairs, holdout_pairs = pairs[:split_idx], pairs[split_idx:]

    train_rows = [to_training_row(t, a) for t, a in train_pairs]
    holdout_rows = [to_training_row(t, a) for t, a in holdout_pairs]

    out_dir = Path(args.out_dir)
    write_jsonl(out_dir / "train.jsonl", train_rows)
    write_jsonl(out_dir / "holdout.jsonl", holdout_rows)

    print(f"Written: {len(train_rows)} train / {len(holdout_rows)} holdout -> {out_dir}/")


if __name__ == "__main__":
    main()
