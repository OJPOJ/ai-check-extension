"""
Baut einen Fine-Tuning-Datensatz fuer die noul-Frage "ist dieser Text KI-generiert?"
im Schema, das Layas Kaggle-Notebook erwartet
(laya_finetune_typed_decisions_2xT4_kaggle.ipynb, siehe ../RESOURCES.md und
README.md in diesem Ordner). Jede Zeile bekommt drei JSON-kodierte Spalten:

    state:     {"candidates": [{"text": "..."}]}
    questions: {"ai_generated": {"type": "noul", "instructions": "..."}}
    gold:      {"ai_generated": {"probabilities": {"true": p, "false": 1 - p}}}

Primaerquelle: HC3 (Hello-SimpleAI/HC3, config "all") - human_answers vs.
chatgpt_answers, pro Frage bereits 1:1 gepaart, dadurch von Natur aus balanciert.
RAID (fuer Robustheit gegen umformulierten/adversarial KI-Text) ist bewusst NICHT
implementiert - das exakte Human-vs-Modell-Zeilenschema wurde in dieser Session nur
aus der Dataset-Card gelesen, nicht an echten Zeilen verifiziert. Siehe README.md.

Nutzung:
    pip install -r requirements.txt
    python prepare_dataset.py --out-dir data --limit 2000   # Smoke-Test, klein
    python prepare_dataset.py --out-dir data                # voller Datensatz
"""

import argparse
import json
import random
from pathlib import Path

# an content.js (extension/content.js) angelehnt, damit Trainings- und
# Inferenzverteilung von Textlaenge zusammenpassen
MIN_WORDS = 40
MAX_CHARS = 500

AI_GENERATED_INSTRUCTIONS = (
    "Is this text primarily generated by an AI/LLM, rather than written by a human? "
    "Judge only the writing style/patterns, not the topic or correctness."
)

# weiche statt harte Labels (0.95/0.05 statt 1.0/0.0), damit das Modell nicht
# ueberkonfident kalibriert wird - passend zum RLCD/proper-scoring-rule-Training
# des Notebooks
SOFT_LABEL = 0.95


def word_count(text: str) -> int:
    return len(text.split())


def iter_hc3_pairs(source: str = "all"):
    """Liefert (text, is_ai) Paare aus HC3. Erfordert `datasets`.

    HC3s eigenes Lade-Script (`name=<subset>`) wird von aktuellen `datasets`-
    Versionen nicht mehr unterstuetzt ("Dataset scripts are no longer
    supported") - stattdessen ueber den von HF automatisch erzeugten
    Parquet-Branch laden (ein Split mit allen Domaenen, `source`-Spalte
    unterscheidet reddit_eli5/finance/medicine/open_qa/wiki_csai).
    """
    from datasets import load_dataset

    ds = load_dataset("Hello-SimpleAI/HC3", revision="refs/convert/parquet")
    split = ds["train"] if "train" in ds else next(iter(ds.values()))
    if source != "all":
        split = split.filter(lambda r: r["source"] == source)

    for row in split:
        for human_text in row.get("human_answers") or []:
            yield human_text, False
        for ai_text in row.get("chatgpt_answers") or []:
            yield ai_text, True


def to_training_row(text: str, is_ai: bool) -> dict:
    text = text.strip()[:MAX_CHARS]
    p_true = SOFT_LABEL if is_ai else (1.0 - SOFT_LABEL)
    state = {"candidates": [{"text": text}]}
    questions = {
        "ai_generated": {"type": "noul", "instructions": AI_GENERATED_INSTRUCTIONS}
    }
    gold = {
        "ai_generated": {
            "probabilities": {"true": round(p_true, 4), "false": round(1 - p_true, 4)}
        }
    }
    return {
        "state": json.dumps(state, ensure_ascii=False),
        "questions": json.dumps(questions, ensure_ascii=False),
        "gold": json.dumps(gold, ensure_ascii=False),
    }


def write_jsonl(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", default="data")
    parser.add_argument("--config", default="all", help="HC3-Domaene (all/finance/medicine/open_qa/reddit_eli5/wiki_csai)")
    parser.add_argument("--min-words", type=int, default=MIN_WORDS)
    parser.add_argument("--train-frac", type=float, default=0.9)
    parser.add_argument("--limit", type=int, default=None, help="Nur die ersten N Paare nehmen (Smoke-Test)")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    random.seed(args.seed)

    pairs = []
    for text, is_ai in iter_hc3_pairs(args.config):
        if word_count(text) < args.min_words:
            continue
        pairs.append((text, is_ai))
        if args.limit and len(pairs) >= args.limit:
            break

    if not pairs:
        raise SystemExit("Keine passenden Beispiele gefunden - HC3-Config/Filter pruefen.")

    n_human = sum(1 for _, is_ai in pairs if not is_ai)
    n_ai = sum(1 for _, is_ai in pairs if is_ai)
    print(f"Gesammelt: {len(pairs)} Beispiele ({n_human} human, {n_ai} KI)")

    random.shuffle(pairs)
    split_idx = int(len(pairs) * args.train_frac)
    train_pairs, holdout_pairs = pairs[:split_idx], pairs[split_idx:]

    train_rows = [to_training_row(t, a) for t, a in train_pairs]
    holdout_rows = [to_training_row(t, a) for t, a in holdout_pairs]

    out_dir = Path(args.out_dir)
    write_jsonl(out_dir / "train.jsonl", train_rows)
    write_jsonl(out_dir / "holdout.jsonl", holdout_rows)

    print(f"Geschrieben: {len(train_rows)} train / {len(holdout_rows)} holdout -> {out_dir}/")


if __name__ == "__main__":
    main()
